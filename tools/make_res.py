#!/usr/bin/env python3
"""Pack the web UI into a CycloneCommon resource array (res.c).

Usage (from the repository root):
    python tools/make_res.py

Every file under F407_smartswitch/web/ is gzip-compressed and stored as
"<path>.gz" in the root directory of the resource image. The CycloneTCP HTTP
server (HTTP_SERVER_GZIP_TYPE_SUPPORT) serves "<uri>.gz" with
Content-Encoding: gzip when the client accepts gzip.

Layout follows resource_manager.h (little-endian, packed):
    ResHeader { uint32 totalSize; ResRootEntry root; }
    ResEntry  { char type; uint32 dataStart; uint32 dataLength;
                uint8 nameLength; char name[]; }
type 1 = directory, 2 = file. Offsets are from the start of res[].
"""
import gzip
import hashlib
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB_DIR = ROOT / "F407_smartswitch" / "web"
OUT = ROOT / "F407_smartswitch" / "Core" / "Src" / "res.c"

RES_TYPE_DIR = 1
RES_TYPE_FILE = 2
HEADER_SIZE = 4 + 10  # totalSize + root entry (type, start, length, nameLength)


def entry(kind, start, length, name):
    raw = name.encode("ascii")
    if len(raw) > 255:
        sys.exit(f"name too long: {name}")
    return struct.pack("<BIIB", kind, start, length, len(raw)) + raw


def build(files):
    names = [name for name, _ in files]
    dir_size = sum(10 + len(n.encode("ascii")) for n in names)
    data_start = HEADER_SIZE + dir_size
    directory, blob, offset = b"", b"", data_start
    for name, data in files:
        directory += entry(RES_TYPE_FILE, offset, len(data), name)
        blob += data
        offset += len(data)
    total = data_start + len(blob)
    header = struct.pack("<I", total) + struct.pack("<BIIB", RES_TYPE_DIR, HEADER_SIZE, dir_size, 0)
    image = header + directory + blob
    assert len(image) == total
    return image


def main():
    sources = sorted(p for p in WEB_DIR.rglob("*") if p.is_file())
    if not sources:
        sys.exit(f"no files in {WEB_DIR}")
    files = []
    for path in sources:
        rel = path.relative_to(WEB_DIR).as_posix()
        if "/" in rel:
            sys.exit(f"subdirectories are not supported yet: {rel}")
        # mtime=0 keeps the output reproducible for identical input.
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        files.append((rel + ".gz", data))
    image = build(files)
    digest = hashlib.sha256(image).hexdigest()[:16]

    lines = [
        "/* Generated by tools/make_res.py from F407_smartswitch/web/. Do not edit. */",
        f"/* Files: {', '.join(n for n, _ in files)}; {len(image)} bytes; sha256 {digest} */",
        "#include <stdint.h>",
        "",
        f"const uint8_t res[{len(image)}] __attribute__((aligned(4))) = {{",
    ]
    for i in range(0, len(image), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in image[i:i + 16]) + ",")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
    for name, data in files:
        print(f"  {name}: {len(data)} bytes")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(image)} bytes, sha256 {digest})")


if __name__ == "__main__":
    main()
